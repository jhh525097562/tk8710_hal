#!/bin/bash
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
test_dir=$(mktemp -d /tmp/tdaemon-dns-test.XXXXXX)
trap 'rm -rf -- "$test_dir"' EXIT
log() { echo "$*"; }
. "$here/tdaemon_dns.sh"
export TDAEMON_DNS_OWNER_FILE="$test_dir/owner"
export TDAEMON_DNS_MAINT_FILE="$test_dir/maintenance"
touch "$TDAEMON_DNS_OWNER_FILE"
ACTIVE_NET_DNS_PRIMARY=223.5.5.5
ACTIVE_NET_DNS_SECONDARY=180.76.76.76
ACTIVE_NET_RESOLV_CONF="$test_dir/resolv.conf"
ln -s target "$ACTIVE_NET_RESOLV_CONF"
printf '# Generated by dhcpcd\nsearch example.test\n' > "$test_dir/target"
dns_ensure_config
test -L "$ACTIVE_NET_RESOLV_CONF"
grep -qx 'search example.test' "$test_dir/target"
test "$(grep -c '^nameserver ' "$test_dir/target")" = 2
inode=$(stat -c %i "$test_dir/target")
dns_ensure_config
test "$inode" = "$(stat -c %i "$test_dir/target")"
printf 'nameserver ::1\n' > "$test_dir/target"
dns_ensure_config
grep -qx 'nameserver 223.5.5.5' "$test_dir/target"
ACTIVE_NET_DNS_PRIMARY=invalid
if dns_ensure_config; then echo 'invalid DNS unexpectedly accepted'; exit 1; fi
grep -qx 'nameserver 223.5.5.5' "$test_dir/target"
ACTIVE_NET_DNS_PRIMARY=223.5.5.5
touch "$TDAEMON_DNS_MAINT_FILE"
: > "$test_dir/target"
dns_ensure_config
test ! -s "$test_dir/target"
rm "$TDAEMON_DNS_MAINT_FILE"
dns_ensure_config
test -s "$test_dir/target"
echo 'PASS: empty/corrupt repair, symlink/search preservation, unchanged inode, invalid config, maintenance guard'
