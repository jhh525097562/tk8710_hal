import os

HTML_FORMAT_FILES = {
    os.path.normpath("web_resources/html/config_mqtt.html"),
    os.path.normpath("web_resources/html/login.html"),
    os.path.normpath("web_resources/html/manger.html"),
    os.path.normpath("web_resources/html/network_diagnostics.html"),
    os.path.normpath("web_resources/html/network_interface.html"),
    os.path.normpath("web_resources/html/status_network.html"),
    os.path.normpath("web_resources/html/status_resources.html"),
    os.path.normpath("web_resources/html/status_system.html"),
    os.path.normpath("web_resources/html/upgrade_firmware.html"),
    os.path.normpath("web_resources/html/upgrade_logs.html"),
    os.path.normpath("web_resources/html/upgrade_maintenance.html"),
}

WEB_RES_DIR = "web_resources"
OUTPUT_FILE = "inc/web_resources.h"

def escape_c_string(s, is_format_string):
    # Escape backslashes first
    s = s.replace('\\', '\\\\')
    # Escape double quotes
    s = s.replace('"', '\\"')
    if is_format_string:
        s = escape_printf_percent(s)
    # Handle newlines: replace actual newline with \n" \n    "
    # This creates a multiline C string literal
    s = s.replace('\n', '\\n"\n    "')
    return s

def escape_printf_percent(s):
    out = []
    i = 0
    n = len(s)
    while i < n:
        if s[i] != '%':
            out.append(s[i])
            i += 1
            continue
        if i + 1 < n and s[i + 1] == '%':
            out.append('%%')
            i += 2
            continue
        j = i + 1
        while j < n and s[j] in "-+ #0":
            j += 1
        if j < n and s[j] == '*':
            j += 1
        while j < n and s[j].isdigit():
            j += 1
        if j < n and s[j] == '.':
            j += 1
            if j < n and s[j] == '*':
                j += 1
            while j < n and s[j].isdigit():
                j += 1
        if s.startswith('hh', j):
            j += 2
        elif s.startswith('ll', j):
            j += 2
        elif j < n and s[j] in "hlztjL":
            j += 1
        if j < n and s[j] in "diuoxXfFeEgGaAcspn":
            out.append(s[i:j + 1])
            i = j + 1
            continue
        out.append('%%')
        i += 1
    return ''.join(out)

def main():
    # SDK invokes this script from rk3506app/, while Make invokes it from webserver/.
    # Resolve inputs/output against this project in both cases.
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    if not os.path.isdir(WEB_RES_DIR):
        raise FileNotFoundError(WEB_RES_DIR)
    # Ensure output directory exists
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    
    with open(OUTPUT_FILE, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_resources.py */\n")
        out.write("#ifndef WEB_RESOURCES_H\n")
        out.write("#define WEB_RESOURCES_H\n\n")

        for root, dirs, files in os.walk(WEB_RES_DIR):
            for file in files:
                if not (file.endswith(".css") or file.endswith(".html") or file.endswith(".js")):
                    continue
                
                path = os.path.join(root, file)
                # Normalize variable name: RES_SUBDIR_FILENAME_EXT
                # e.g. web_resources/css/style.css -> RES_CSS_STYLE_CSS
                rel_path = os.path.relpath(path, WEB_RES_DIR)
                var_name = "RES_" + rel_path.replace(os.sep, "_").replace(".", "_").upper()
                
                try:
                    with open(path, "r", encoding="utf-8") as f:
                        content = f.read()
                    
                    is_format_string = os.path.normpath(path) in HTML_FORMAT_FILES
                    c_content = escape_c_string(content, is_format_string)
                    
                    out.write(f'static const char *{var_name} = \n    "{c_content}";\n\n')
                    print(f"Generated {var_name} from {rel_path}")
                except Exception as e:
                    print(f"Error processing {path}: {e}")
        
        out.write("#endif // WEB_RESOURCES_H\n")

if __name__ == "__main__":
    main()
