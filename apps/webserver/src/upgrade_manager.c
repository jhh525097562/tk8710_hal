#include "upgrade_manager.h"
#include "file_logger.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <pthread.h>
#include <unistd.h>
#include <sys/wait.h>
#include <fcntl.h>
#include <errno.h>
#include <sys/stat.h>

#define WEB_FILE_LOG "/var/log/web_server.log"
#define INSTALL_IMAGE "/tmp/image.installing.swu"
static pthread_mutex_t status_lock = PTHREAD_MUTEX_INITIALIZER;
static UpgradeStatus current_status = UPGRADE_IDLE;
static char status_message[256] = "";

static void set_status(UpgradeStatus status, const char *message)
{
    pthread_mutex_lock(&status_lock);
    current_status = status;
    snprintf(status_message, sizeof(status_message), "%s", message);
    pthread_mutex_unlock(&status_lock);
}

static int run_update(int check, const char *tempdir)
{
    char tmpenv[160];
    char ownerenv[160];
    snprintf(tmpenv, sizeof(tmpenv), "TMPDIR=%s/", tempdir);
    snprintf(ownerenv, sizeof(ownerenv), "APP_UPGRADE_OWNER=%s", tempdir);
    pid_t child = fork();
    if (child < 0) return -1;
    if (child == 0) {
        int fd = open("/tmp/swupdate.log", O_CREAT | O_WRONLY | O_APPEND, 0600);
        if (fd >= 0) { dup2(fd, 1); dup2(fd, 2); if (fd > 2) close(fd); }
        /* Isolate extraction files. Base firmware disables the fixed-socket daemon. */
        if (check) execlp("env", "env", tmpenv, ownerenv, "/usr/bin/swupdate", "-v", "-c", "-i", INSTALL_IMAGE, "-e", "stable,copy1", (char *)NULL);
        else execlp("env", "env", tmpenv, ownerenv, "/usr/bin/swupdate", "-v", "-i", INSTALL_IMAGE, "-e", "stable,copy1", (char *)NULL);
        _exit(127);
    }
    int status;
    while (waitpid(child, &status, 0) < 0) {
        if (errno != EINTR) return -1;
    }
    return WIFEXITED(status) ? WEXITSTATUS(status) : -1;
}

static void *upgrade_thread_func(void *unused)
{
    (void)unused;
    int fd = open("/tmp/swupdate.log", O_CREAT | O_TRUNC | O_WRONLY, 0600);
    if (fd >= 0) close(fd);
    if (system("pidof swupdate swupdate-progress >/dev/null 2>&1") == 0) {
        set_status(UPGRADE_ERROR, "Another SWUpdate/progress process is running; stop the legacy updater first");
        return NULL;
    }
    char tempdir[] = "/tmp/web-swupdate-XXXXXX";
    if (!mkdtemp(tempdir)) {
        set_status(UPGRADE_ERROR, "Cannot create private update directory");
        return NULL;
    }
    int checked = run_update(1, tempdir);
    int result = checked == 0 ? run_update(0, tempdir) : checked;
    if (result == 0) {
        set_status(UPGRADE_DONE, "Upgrade successful. Rebooting...");
        file_logger_write(WEB_FILE_LOG, "INFO", "upgrade completed");
        system("mkdir -p /userdata/.app-upgrade && cp /tmp/swupdate.log /userdata/.app-upgrade/last-swupdate.log");
        unlink(INSTALL_IMAGE);
        sleep(3);
        sync();
        /* Successful command-line installation does not reboot; the Web owns it. */
        system("reboot");
    } else {
        int recovery = 0;
        if (checked == 0) {
            char command[256];
            /* tempdir is generated by mkdtemp, never supplied by the HTTP client. */
            snprintf(command, sizeof(command), "APP_UPGRADE_OWNER=%s /usr/bin/app_upgrade.sh recover >>/tmp/swupdate.log 2>&1", tempdir);
            recovery = system(command);
        }
        system("mkdir -p /userdata/.app-upgrade && cp /tmp/swupdate.log /userdata/.app-upgrade/last-swupdate.log");
        char message[256];
        snprintf(message, sizeof(message), "Upgrade failed (code=%d, recovery=%d). See /tmp/swupdate.log", result, recovery);
        set_status(UPGRADE_ERROR, message);
        file_logger_write(WEB_FILE_LOG, "ERROR", "%s", message);
    }
    return NULL;
}

bool upgrade_start(const char *file_path)
{
    if (!file_path || strcmp(file_path, "/tmp/image.swu")) return false;
    /* Base firmware must provide recovery before application-only upgrades. */
    if (access("/usr/bin/app_upgrade.sh", X_OK) || access("/etc/init.d/S98app_upgrade_recover", X_OK)) {
        set_status(UPGRADE_ERROR, "Base firmware lacks application upgrade recovery");
        return false;
    }
    pthread_mutex_lock(&status_lock);
    if (current_status == UPGRADE_INSTALLING || current_status == UPGRADE_DONE) {
        pthread_mutex_unlock(&status_lock); return false;
    }
    if (rename(file_path, INSTALL_IMAGE)) {
        pthread_mutex_unlock(&status_lock); return false;
    }
    current_status = UPGRADE_INSTALLING;
    snprintf(status_message, sizeof(status_message), "Checking and installing application bundle...");
    pthread_t thread;
    if (pthread_create(&thread, NULL, upgrade_thread_func, NULL)) {
        current_status = UPGRADE_ERROR;
        snprintf(status_message, sizeof(status_message), "Cannot create upgrade worker");
        rename(INSTALL_IMAGE, file_path);
        pthread_mutex_unlock(&status_lock); return false;
    }
    pthread_detach(thread);
    pthread_mutex_unlock(&status_lock);
    return true;
}

void upgrade_get_status(UpgradeStatus *status, char *message, size_t length)
{
    pthread_mutex_lock(&status_lock);
    *status = current_status;
    if (length) snprintf(message, length, "%s", status_message);
    pthread_mutex_unlock(&status_lock);
}
