#!/bin/sh
# DNS ownership is enabled by /etc/tdaemon-dns-owner in the base firmware.
dns_valid_ipv4() {
    printf '%s\n' "$1" | awk -F. '
        NR != 1 || NF != 4 {exit 1}
        {for(i=1;i<=4;i++) if($i !~ /^[0-9]+$/ || length($i)>3 || $i+0>255) exit 1}
    '
}

dns_ensure_config() {
    [ -e "${TDAEMON_DNS_OWNER_FILE:-/etc/tdaemon-dns-owner}" ] || return 0
    [ ! -e "${TDAEMON_DNS_MAINT_FILE:-/var/run/app-upgrade-maintenance}" ] || return 0
    local primary="${ACTIVE_NET_DNS_PRIMARY:-}"
    local secondary="${ACTIVE_NET_DNS_SECONDARY:-}"
    if ! dns_valid_ipv4 "$primary" || { [ -n "$secondary" ] && ! dns_valid_ipv4 "$secondary"; }; then
        log ERROR "DNS配置非法，保留当前解析文件；检查tdaemon.conf的dns_primary/dns_secondary"
        return 1
    fi
    local target wanted current temporary
    target=$(readlink -f "${ACTIVE_NET_RESOLV_CONF:-/etc/resolv.conf}") || return 1
    [ -n "$target" ] || return 1
    [ ! -e "$target" ] || [ -f "$target" ] || return 1
    wanted=$(printf 'nameserver %s\n' "$primary"; [ -z "$secondary" ] || [ "$secondary" = "$primary" ] || printf 'nameserver %s\n' "$secondary")
    current=$(awk '$1=="nameserver" {print "nameserver " $2}' "$target" 2>/dev/null || true)
    [ "$current" != "$wanted" ] || return 0
    temporary=$(mktemp "$target.tdaemon.XXXXXX") || return 1
    # Preserve search/domain/options while replacing only the managed DNS entries.
    if ! {
        printf '# DNS servers managed by tdaemon\n'
        if [ -f "$target" ]; then
            awk '$1!="nameserver" && $0!="# DNS servers managed by tdaemon" && $0!="# Generated by dhcpcd"' "$target"
        fi
        printf '%s\n' "$wanted"
    } > "$temporary"; then
        rm -f "$temporary"
        return 1
    fi
    if ! chmod 644 "$temporary" || ! mv -f "$temporary" "$target"; then
        rm -f "$temporary"
        log ERROR "DNS配置修复失败：$target"
        return 1
    fi
    log WARN "DNS配置已恢复：primary=$primary secondary=$secondary target=$target"
}
