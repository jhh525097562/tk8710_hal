static void tk8710BringupLogHex32(uint32 value)
{
    sint32 shift;
    uint8 nibble;
    uint8 ch;

    tk8710BringupLog("0x");
    for (shift = 28; shift >= 0; shift -= 4) {
        nibble = (uint8)((value >> (uint32)shift) & 0x0FU);
        ch = (uint8)((nibble < 10U) ? ((uint8)'0' + nibble) : ((uint8)'A' + nibble - 10U));
        while (sciIsTxReady(scilinREG) == 0U) {
        }
        sciSendByte(scilinREG, ch);
    }
}

