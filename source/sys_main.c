static void tk8710BringupLogDecU64(uint64_t value)
{
    char text[24];
    uint32_t index = 0U;
    char rev[24];

    if (value == 0ULL) {
        tk8710BringupLog("0");
        return;
    }

    while ((value != 0ULL) && (index < (uint32_t)sizeof(rev))) {
        rev[index++] = (char)('0' + (uint8_t)(value % 10ULL));
        value /= 10ULL;
    }

    {
        uint32_t outIndex = 0U;
        while (index > 0U) {
            text[outIndex++] = rev[--index];
        }
        text[outIndex] = '\0';
    }

    tk8710BringupLog(text);
}

