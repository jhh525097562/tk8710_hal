static int tk8710AtReadLine(char* buffer, uint32 maxLen)
{
    static uint32 index = 0U;
    static uint32 overflow = 0U;

    while (sciIsRxReady(scilinREG) != 0U) {
        uint32 raw = sciReceiveByte(scilinREG);
        char ch = (char)(raw & 0xFFU);

        if (ch == '\r' || ch == '\n') {
            tk8710BringupLog("\r\n");

            if (overflow != 0U) {
                index = 0U;
                overflow = 0U;
                tk8710BringupLog("ERROR command too long\r\n");
                return 0;
            }

            if (index == 0U) {
                continue;
            }

            buffer[index] = '\0';
            index = 0U;
            tk8710BringupLog(buffer);
            tk8710BringupLog("\r\n");
            return 1;
        }

        if ((ch == '\b' || ch == 0x7FU) && index > 0U) {
            index--;
            continue;
        }

        if (!isprint((unsigned char)ch)) {
            continue;
        }

        if (index < (maxLen - 1U)) {
            buffer[index++] = ch;
        } else {
            overflow = 1U;
        }
    }

    return 0;
}

static int tk8710AtParseU32(const char* text, uint32* value)
{
    char* endPtr;
    unsigned long parsed;

    if (text == NULL || value == NULL || *text == '\0') {
        return -1;
    }

    parsed = strtoul(text, &endPtr, 0);
    if (*endPtr != '\0') {
        return -1;
    }

    *value = (uint32)parsed;
    return 0;
}

static int tk8710AtParseMasterParams(char* text, uint32_t* params, uint32_t paramCount)
{
    uint32_t i;
    char* current;
    char* endPtr;
    unsigned long parsed;

    if ((text == NULL) || (params == NULL) || (paramCount == 0U)) {
        return -1;
    }

    current = text;
    for (i = 0U; i < paramCount; i++) {
        while ((*current == ' ') || (*current == '\t')) {
            current++;
        }

        if (*current == '\0') {
            tk8710BringupLog("ERROR missing master arg index=");
            tk8710BringupLogDecU32(i);
            tk8710BringupLog("\r\n");
            return -1;
        }

        parsed = strtoul(current, &endPtr, 0);
        if (endPtr == current) {
            tk8710BringupLog("ERROR bad master arg index=");
            tk8710BringupLogDecU32(i);
            tk8710BringupLog("\r\n");
            return -1;
        }

        while ((*endPtr == ' ') || (*endPtr == '\t')) {
            endPtr++;
        }

        if (i < (paramCount - 1U)) {
            if (*endPtr != ',') {
                tk8710BringupLog("ERROR missing comma after master arg index=");
                tk8710BringupLogDecU32(i);
                tk8710BringupLog("\r\n");
                return -1;
            }
            current = endPtr + 1;
        } else {
            if (*endPtr != '\0') {
                tk8710BringupLog("ERROR trailing master args\r\n");
                return -1;
            }
        }

        params[i] = (uint32_t)parsed;
    }

    return 0;
}

static int tk8710AtHandleCommand(char* line)
{
    int ret;
    uint32_t value;
    char* arg0;
    char* arg1;
    char* arg2;

    if (line == NULL) {
        tk8710BringupLog("ERROR\r\n");
        return -1;
    }

    while (*line == ' ' || *line == '\t') {
        line++;
    }

    if (*line == '\0') {
        return 0;
    }

    if (strcmp(line, "AT") == 0) {
        tk8710BringupLog("OK\r\n");
        return 0;
    }

    if (strcmp(line, "AT+HELP") == 0) {
        tk8710AtPrintHelp();
        tk8710BringupLog("OK\r\n");
        return 0;
    }

    if (strncmp(line, "AT+RUN=", 7) == 0) {
        ret = tk8710AtRunTest(line + 7);
        tk8710BringupLog((ret == 0) ? "OK\r\n" : "ERROR\r\n");
        return ret;
    }

    if (strcmp(line, "AT+BRREG") == 0) {
        ret = tk8710RunBurstRegTest();
        tk8710BringupLog((ret == 0) ? "OK\r\n" : "ERROR\r\n");
        return ret;
    }

    if (strcmp(line, "AT+BBUF") == 0) {
        ret = tk8710RunBurstBufferTest();
        tk8710BringupLog((ret == 0) ? "OK\r\n" : "ERROR\r\n");
        return ret;
    }

    if (strcmp(line, "AT+IRQSTAT") == 0) {
        tk8710AtPrintIrqStats();
        tk8710BringupLog("OK\r\n");
        return 0;
    }

    if (strncmp(line, "AT+RREG=", 8) == 0) {
        if (tk8710AtParseU32(line + 8, &value) != 0) {
            tk8710BringupLog("ERROR bad addr\r\n");
            return -1;
        }

        ret = TK8710ReadReg(TK8710_REG_TYPE_GLOBAL, (uint16_t)value, &value);
        if (ret != TK8710_OK) {
            tk8710BringupLog("ERROR read ret=");
            tk8710BringupLogDecU32((uint32)ret);
            tk8710BringupLog("\r\n");
            return -1;
        }

        tk8710BringupLog("REG=");
        tk8710BringupLogHex32(value);
        tk8710BringupLog("\r\nOK\r\n");
        return 0;
    }

    if (strncmp(line, "AT+WREG=", 8) == 0) {
        uint32_t addr;
        uint32_t data;

        arg0 = line + 8;
        arg1 = strchr(arg0, ',');
        if (arg1 == NULL) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }
        *arg1++ = '\0';

        if (tk8710AtParseU32(arg0, &addr) != 0 || tk8710AtParseU32(arg1, &data) != 0) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }

        ret = TK8710WriteReg(TK8710_REG_TYPE_GLOBAL, (uint16_t)addr, data);
        if (ret != TK8710_OK) {
            tk8710BringupLog("ERROR write ret=");
            tk8710BringupLogDecU32((uint32)ret);
            tk8710BringupLog("\r\n");
            return -1;
        }

        tk8710BringupLog("OK\r\n");
        return 0;
    }

    if (strncmp(line, "AT+RRF=", 7) == 0) {
        uint32_t rfSel;
        uint32_t addr;

        arg0 = line + 7;
        arg1 = strchr(arg0, ',');
        if (arg1 == NULL) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }
        *arg1++ = '\0';

        if (tk8710AtParseU32(arg0, &rfSel) != 0 || tk8710AtParseU32(arg1, &addr) != 0) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }

        ret = tk8710_rf_read((uint8_t)rfSel, (uint16_t)addr, &value);
        if (ret != TK8710_OK) {
            tk8710BringupLog("ERROR rf read ret=");
            tk8710BringupLogDecU32((uint32)ret);
            tk8710BringupLog("\r\n");
            return -1;
        }

        tk8710BringupLog("RF=");
        tk8710BringupLogHex32(value);
        tk8710BringupLog("\r\nOK\r\n");
        return 0;
    }

    if (strncmp(line, "AT+WRF=", 7) == 0) {
        uint32_t rfSel;
        uint32_t addr;
        uint32_t data;

        arg0 = line + 7;
        arg1 = strchr(arg0, ',');
        if (arg1 == NULL) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }
        *arg1++ = '\0';
        arg2 = strchr(arg1, ',');
        if (arg2 == NULL) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }
        *arg2++ = '\0';

        if (tk8710AtParseU32(arg0, &rfSel) != 0 ||
            tk8710AtParseU32(arg1, &addr) != 0 ||
            tk8710AtParseU32(arg2, &data) != 0) {
            tk8710BringupLog("ERROR bad args\r\n");
            return -1;
        }

        ret = tk8710_rf_write((uint8_t)rfSel, (uint16_t)addr, data);
        if (ret != TK8710_OK) {
            tk8710BringupLog("ERROR rf write ret=");
            tk8710BringupLogDecU32((uint32)ret);
            tk8710BringupLog("\r\n");
            return -1;
        }

        tk8710BringupLog("OK\r\n");
        return 0;
    }

    tk8710BringupLog("ERROR unknown command\r\n");
    return -1;
}

