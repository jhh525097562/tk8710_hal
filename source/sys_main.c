static int tk8710BurstWriteRegBytes(uint16_t addr, const uint8_t* data, uint32_t len)
{
    if ((data == NULL) || (len == 0U) || ((3U + len) > sizeof(g_tk8710LoopbackSpiBuf))) {
        return -1;
    }

    g_tk8710LoopbackSpiBuf[0] = TK8710_SPI_CMD_WR_REG;
    g_tk8710LoopbackSpiBuf[1] = (uint8_t)(addr >> 8);
    g_tk8710LoopbackSpiBuf[2] = (uint8_t)(addr & 0xFFU);
    memcpy(&g_tk8710LoopbackSpiBuf[3], data, len);

    return TK8710SpiWrite(g_tk8710LoopbackSpiBuf, (size_t)(3U + len));
}

static int tk8710BurstReadRegBytes(uint16_t addr, uint8_t* data, uint32_t len)
{
    uint32_t i;

    if ((data == NULL) || (len == 0U) || ((4U + len) > sizeof(g_tk8710LoopbackSpiBuf))) {
        return -1;
    }

    for (i = 0U; i < (4U + len); i++) {
        g_tk8710LoopbackSpiBuf[i] = TK8710_NOP_BYTE;
    }
    g_tk8710LoopbackSpiBuf[0] = TK8710_SPI_CMD_RD_REG;
    g_tk8710LoopbackSpiBuf[1] = (uint8_t)(addr >> 8);
    g_tk8710LoopbackSpiBuf[2] = (uint8_t)(addr & 0xFFU);

    if (TK8710SpiTransfer(g_tk8710LoopbackSpiBuf,
                          g_tk8710LoopbackSpiBuf,
                          (size_t)(4U + len)) != 0) {
        return -1;
    }

    memmove(data, &g_tk8710LoopbackSpiBuf[4], len);
    return 0;
}

